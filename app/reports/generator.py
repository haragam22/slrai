"""
Report generation service.

Called by tasks.chain_b.task_generate_report at the end of Chain B.

FLOW:
  1. build_report_context(case_id, db) — assembles full dict from PostgreSQL
  2. _render_template(context)          — Jinja2 → HTML string
  3. WeasyPrint → PDF bytes             — on failure, save JSON only (non-fatal)
  4. upload_report_pdf / _json → S3
  5. Insert Report row in DB

DRT STAY GATE:
  If drt_interim_stay_granted == True in case facts, override recommendation
  to DO_NOT_PROCEED_CRITICAL regardless of computed score.
"""

